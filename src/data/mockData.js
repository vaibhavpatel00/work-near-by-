const generateNearbyCoord = (baseLat, baseLng, radiusKm = 5) => {
  const r = radiusKm / 111.32;
  const angle = Math.random() * 2 * Math.PI;
  const dist = Math.random() * r;
  return {
    lat: baseLat + dist * Math.cos(angle),
    lng: baseLng + dist * Math.sin(angle),
  };
};

