export const DEFAULT_COUNTRY = COUNTRIES.find(c => c.code === 'US') || COUNTRIES[0];

export const getCountryByCode = (code) => {
  if (!code) return DEFAULT_COUNTRY;
  return COUNTRIES.find(c => c.code.toUpperCase() === code.toUpperCase()) || DEFAULT_COUNTRY;
};

export const getCountryByDialCode = (dialCode) => {
  if (!dialCode) return DEFAULT_COUNTRY;
  const cleanCode = dialCode.startsWith('+') ? dialCode : '+' + dialCode;
  return COUNTRIES.find(c => c.dialCode === cleanCode) || DEFAULT_COUNTRY;
};
